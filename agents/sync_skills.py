#!/usr/bin/env python3
"""
Install the skills chosen in ``skills.conf`` into the agents chosen there.

Two mechanisms, because agents disagree about how they load instructions:

1. Skill directories. Each enabled skill is linked into the agent's skill
   directory (Claude Code, Codex, opencode, ...). The source stays the source
   of truth — editing a skill here updates the agent immediately.
2. A digest file. Agents without skill support read a single instructions file
   (``AGENTS.md``, ``copilot-instructions.md``, ``GEMINI.md``). One is generated
   with the always-on skills inlined and the rest indexed by absolute path, then
   spliced into a managed block so anything hand-written around it survives.

Claude Code gets both: its skill directory, and the always-on skills inlined
into ``~/.claude/CLAUDE.md`` (without the index, since it sees every skill's
description on its own). Otherwise "always on" would mean nothing there, as a
skill is only read when invoked.

Skills and agents are picked in ``skills.conf``. Agents that aren't listed have
anything this script installed removed. Without ``agent`` lines, every agent
whose config directory exists is used.
"""

import argparse
import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Dict, List, Optional, Tuple

DIR_REPO = Path(__file__).resolve().parent
FILEPATH_CONF = DIR_REPO / "skills.conf"

MARKER_BEGIN = "<!-- BEGIN agent_skills: generated by sync_skills.py, do not edit inside -->"
MARKER_END = "<!-- END agent_skills -->"

SKILLS_ALWAYS = (
    "coding-style",
    "workspace-conventions",
    "data-management",
    "runhub",
    "deslop",
)

TARGETS_SKILLS = {
    "claude": Path.home() / ".claude" / "skills",
    "codex": Path.home() / ".codex" / "skills",
    "agents": Path.home() / ".agents" / "skills",
    "opencode": Path.home() / ".config" / "opencode" / "skills",
    "gemini": Path.home() / ".gemini" / "skills",
    "cursor": Path.home() / ".cursor" / "skills",
}

TARGETS_DIGEST = {
    "repo": DIR_REPO / "AGENTS.md",
    "claude": Path.home() / ".claude" / "CLAUDE.md",
    "codex": Path.home() / ".codex" / "AGENTS.md",
    "copilot": Path.home() / ".copilot" / "copilot-instructions.md",
    "gemini": Path.home() / ".gemini" / "GEMINI.md",
    "opencode": Path.home() / ".config" / "opencode" / "AGENTS.md",
    "cursor": Path.home() / ".cursor" / "AGENTS.md",
}


def parse_skill(filepath_skill: Path) -> Tuple[str, str, str]:
    """
    Split a SKILL.md into name, description, and body.

    Parameters
    ----------
    filepath_skill : Path
        Path to a SKILL.md with YAML frontmatter.

    Returns
    -------
    tuple of str
        ``(name, description, body)``. The body excludes the frontmatter.

    Raises
    ------
    ValueError
        If the file has no frontmatter block.
    """
    text = filepath_skill.read_text(encoding="utf-8")
    if not text.startswith("---"):
        raise ValueError(f"{filepath_skill} has no frontmatter")
    _, frontmatter, body = text.split("---", 2)

    fields = {}
    for line in frontmatter.strip().splitlines():
        if ":" not in line:
            continue
        key, value = line.split(":", 1)
        fields[key.strip()] = value.strip().strip("\"'")

    name = fields.get("name", filepath_skill.parent.name)
    return name, fields.get("description", ""), body.strip()


def read_conf() -> Tuple[List[Path], List[str], Optional[List[str]]]:
    """
    Parse ``skills.conf``.

    Returns
    -------
    tuple
        ``(sources, names, agents)``. `sources` are skill directories in search
        order, `names` the enabled skills, `agents` the listed agents or ``None``
        when there are no ``agent`` lines.
    """
    sources, names, agents = [], [], []
    for line in FILEPATH_CONF.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        key, _, value = line.partition(" ")
        if key == "source":
            sources.append((DIR_REPO / value.strip()).resolve())
        elif key == "agent":
            agents.append(value.strip())
        else:
            names.append(line)
    return sources, names, agents or None


def collect_skills(sources: List[Path], names: List[str]) -> List[Dict[str, object]]:
    """
    Read each enabled skill from the first source that has it.

    Parameters
    ----------
    sources : list of Path
        Skill directories, searched in order. Missing ones are skipped.
    names : list of str
        Enabled skill names.

    Returns
    -------
    list of dict
        One entry per skill found, with keys ``name``, ``description``, ``body``, ``dir``.
    """
    skills = []
    for name in names:
        dir_skill = next((d / name for d in sources if (d / name / "SKILL.md").is_file()), None)
        if dir_skill is None:
            print(f"  skipped  {name} (not in any source)")
            continue
        skill_name, description, body = parse_skill(dir_skill / "SKILL.md")
        skills.append({"name": skill_name, "description": description, "body": body, "dir": dir_skill})
    return skills


def is_managed(target: Optional[str], sources: List[Path]) -> bool:
    """Whether a link points into one of the skill sources, i.e. this script owns it."""
    if target is None:
        return False
    return any(target.lower().startswith(str(d).lower() + os.sep) for d in sources)


def read_link(path: Path) -> Optional[str]:
    """
    Resolve a symlink or Windows junction to its target.

    Parameters
    ----------
    path : Path
        Candidate link.

    Returns
    -------
    str or None
        Absolute target path, or ``None`` if `path` is not a link.
    """
    try:
        target = os.readlink(path)
    except OSError:
        return None
    if target.startswith("\\\\?\\"):
        target = target[4:]  ## junctions report an extended-length path
    return str(Path(target.rstrip("\\/")).absolute())


def make_link(dir_source: Path, path_link: Path) -> str:
    """
    Point `path_link` at `dir_source`, degrading gracefully on Windows.

    Symlinks need Developer Mode or admin on Windows; a directory junction needs
    neither. A copy is the last resort and is a snapshot, not a live link.

    Parameters
    ----------
    dir_source : Path
        Skill directory in this repo.
    path_link : Path
        Location to create inside an agent skill directory.

    Returns
    -------
    str
        The mechanism used: ``"symlink"``, ``"junction"``, or ``"copy"``.
    """
    if os.name != "nt":
        os.symlink(dir_source, path_link, target_is_directory=True)
        return "symlink"

    try:
        os.symlink(dir_source, path_link, target_is_directory=True)
        return "symlink"
    except OSError:
        pass

    result = subprocess.run(
        ["cmd", "/c", "mklink", "/J", str(path_link), str(dir_source)],
        capture_output=True,
    )
    if result.returncode == 0:
        return "junction"

    shutil.copytree(dir_source, path_link)
    return "copy"


def remove_link(path: Path) -> None:
    """Delete a link, or the directory tree left behind by a copy fallback."""
    if read_link(path) is not None or path.is_file():
        path.unlink()
    else:
        shutil.rmtree(path)


def sync_skill_dir(dir_target: Path, skills: List[Dict[str, object]], sources: List[Path], dry_run: bool) -> None:
    """
    Link every skill into one agent skill directory and drop stale entries.

    Parameters
    ----------
    dir_target : Path
        An agent's skills directory.
    skills : list of dict
        Output of :func:`collect_skills`. Empty removes every managed link.
    sources : list of Path
        Skill sources; links into these that aren't enabled are removed.
    dry_run : bool
        Report the plan without touching the filesystem.
    """
    print(f"  skills -> {dir_target}")
    if not dry_run:
        dir_target.mkdir(parents=True, exist_ok=True)

    dirs_enabled = {skill["dir"] for skill in skills}
    if dir_target.is_dir():
        for path_existing in sorted(dir_target.iterdir()):
            target = read_link(path_existing)
            if not is_managed(target, sources):
                continue
            if Path(target) in dirs_enabled and path_existing.name == Path(target).name:
                continue
            print(f"    removed  {path_existing.name} ({'not enabled' if skills else 'agent not selected'})")
            if not dry_run:
                remove_link(path_existing)

    counts = {"added": 0, "relinked": 0, "unchanged": 0}
    for skill in skills:
        dir_source = skill["dir"]
        path_link = dir_target / dir_source.name
        target = read_link(path_link)
        if target is not None and Path(target) == dir_source:
            counts["unchanged"] += 1
            continue

        exists = path_link.exists() or target is not None
        counts["relinked" if exists else "added"] += 1
        if dry_run:
            print(f"    {'relink' if exists else 'add'}     {dir_source.name}")
            continue

        if exists:
            remove_link(path_link)
        mechanism = make_link(dir_source, path_link)
        print(f"    {'relinked' if exists else 'added'}   {dir_source.name} ({mechanism})")

    print(f"    {counts['added']} added, {counts['relinked']} relinked, {counts['unchanged']} unchanged")


def demote_headings(body: str, levels: int = 2) -> str:
    """
    Push every Markdown heading down by `levels` so an inlined skill nests under
    the digest's own headings instead of competing with them.

    Parameters
    ----------
    body : str
        Skill body, frontmatter already stripped.
    levels : int
        Number of ``#`` to prepend. Headings are clamped at level 6.

    Returns
    -------
    str
        Body with headings demoted. Fenced code blocks are left untouched.
    """
    lines = []
    in_fence = False
    for line in body.splitlines():
        if line.lstrip().startswith("```"):
            in_fence = not in_fence
        depth = len(line) - len(line.lstrip("#"))
        if not in_fence and depth and line[depth : depth + 1] == " ":
            line = "#" * min(depth + levels, 6) + line[depth:]
        lines.append(line)
    return "\n".join(lines)


def build_digest(skills: List[Dict[str, object]], relative: bool = False, index: bool = True) -> str:
    """
    Render the managed-block body for agents that read a single instructions file.

    Always-on skills are inlined verbatim. The rest become an index the agent
    reads on demand, which is how skills work anyway.

    Parameters
    ----------
    skills : list of dict
        Output of :func:`collect_skills`.
    relative : bool
        Write skill paths relative to the repo. Use for the digest committed to
        this repo; absolute paths are needed for digests installed elsewhere.
    index : bool
        Append the on-demand index. Off for an agent that loads skills itself.

    Returns
    -------
    str
        Markdown body, without the surrounding markers.
    """
    source = "this repository" if relative else f"`{DIR_REPO}`"
    lines = [
        "# Agent skills",
        "",
        f"Source of truth: {source}. Regenerate with `python sync_skills.py`.",
        "",
        "## Always apply",
        "",
    ]
    for name in SKILLS_ALWAYS:
        skill = next((s for s in skills if s["name"] == name), None)
        if skill is None:
            continue
        lines += [demote_headings(str(skill["body"])), ""]

    if not index:
        return "\n".join(lines).strip() + "\n"

    lines += [
        "## Load on demand",
        "",
        "Read the SKILL.md in full before starting work it covers.",
        "",
        "| skill | use it when | path |",
        "| --- | --- | --- |",
    ]
    for skill in skills:
        if skill["name"] in SKILLS_ALWAYS:
            continue
        filepath_skill = skill["dir"] / "SKILL.md"
        if relative and filepath_skill.is_relative_to(DIR_REPO):
            filepath_skill = filepath_skill.relative_to(DIR_REPO).as_posix()
        description = str(skill["description"]).replace("|", "\\|")
        lines.append(f"| `{skill['name']}` | {description} | `{filepath_skill}` |")

    return "\n".join(lines).strip() + "\n"


def write_digest(filepath_digest: Path, body: str, dry_run: bool) -> None:
    """
    Splice `body` into `filepath_digest` between the managed markers.

    Text outside the markers is preserved, so hand-written instructions in an
    existing AGENTS.md survive every resync.

    Parameters
    ----------
    filepath_digest : Path
        Destination instructions file.
    body : str
        Output of :func:`build_digest`.
    dry_run : bool
        Report the plan without touching the filesystem.
    """
    block = f"{MARKER_BEGIN}\n\n{body.strip()}\n\n{MARKER_END}"

    existing = filepath_digest.read_text(encoding="utf-8") if filepath_digest.is_file() else ""
    if MARKER_BEGIN in existing and MARKER_END in existing:
        head = existing.split(MARKER_BEGIN)[0]
        tail = existing.split(MARKER_END, 1)[1]
        updated = head + block + tail
        action = "updated"
    elif existing.strip():
        updated = existing.rstrip() + "\n\n" + block + "\n"
        action = "appended to"
    else:
        updated = block + "\n"
        action = "created"

    if updated == existing:
        print(f"  digest == {filepath_digest} (unchanged)")
        return

    print(f"  digest -> {filepath_digest} ({action})")
    if not dry_run:
        filepath_digest.parent.mkdir(parents=True, exist_ok=True)
        filepath_digest.write_text(updated, encoding="utf-8")


def remove_digest(filepath_digest: Path, dry_run: bool) -> None:
    """
    Strip the managed block from an agent that is no longer selected.

    Deletes the file when nothing hand-written is left around the block.

    Parameters
    ----------
    filepath_digest : Path
        Instructions file that may hold a managed block.
    dry_run : bool
        Report the plan without touching the filesystem.
    """
    if not filepath_digest.is_file():
        return
    existing = filepath_digest.read_text(encoding="utf-8")
    if MARKER_BEGIN not in existing or MARKER_END not in existing:
        return
    remaining = (existing.split(MARKER_BEGIN)[0] + existing.split(MARKER_END, 1)[1]).strip()
    print(f"  digest x  {filepath_digest} ({'block removed' if remaining else 'deleted'})")
    if dry_run:
        return
    if remaining:
        filepath_digest.write_text(remaining + "\n", encoding="utf-8")
    else:
        filepath_digest.unlink()


def select_targets(targets: Dict[str, Path], names: Optional[List[str]], install_all: bool) -> Dict[str, Path]:
    """
    Keep the targets that should be written this run.

    Parameters
    ----------
    targets : dict
        Agent name to destination path.
    names : list of str, optional
        Agent names from ``--agent`` or ``skills.conf``. ``None`` means autodetect.
    install_all : bool
        Write every known target even when the agent is not installed.

    Returns
    -------
    dict
        The subset to write.
    """
    if names is not None:
        return {name: path for name, path in targets.items() if name in names}
    if install_all:
        return dict(targets)
    return {name: path for name, path in targets.items() if path.parent.is_dir()}


def main() -> int:
    """Parse arguments and run the sync."""
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--agent", action="append", dest="agents", help="Sync only this agent, overriding skills.conf. Repeatable.")
    parser.add_argument("--all", action="store_true", help="Write every known target, installed or not.")
    parser.add_argument("--dry-run", action="store_true", help="Show what would change.")
    parser.add_argument("--skills-only", action="store_true", help="Skip digest generation.")
    parser.add_argument("--digest-only", action="store_true", help="Skip skill linking.")
    parser.add_argument("--list", action="store_true", help="List known agents and whether each is detected.")
    args = parser.parse_args()

    sources, names, agents_conf = read_conf()
    agents = args.agents or agents_conf

    if args.list:
        selected = set(select_targets(TARGETS_SKILLS, agents, args.all)) | set(select_targets(TARGETS_DIGEST, agents, args.all))
        for name in sorted(set(TARGETS_SKILLS) | set(TARGETS_DIGEST)):
            paths = [t[name] for t in (TARGETS_SKILLS, TARGETS_DIGEST) if name in t]
            detected = any(path.parent.is_dir() for path in paths)
            state = "selected" if name in selected else "detected" if detected else "--"
            print(f"{state:>8}  {name}")
            for path in paths:
                print(f"          {path}")
        return 0

    skills = collect_skills(sources, names)
    if not skills:
        print(f"no enabled skills found, check {FILEPATH_CONF}", file=sys.stderr)
        return 1
    print(f"{len(skills)} skills enabled in {FILEPATH_CONF.name}")

    if not args.digest_only:
        selected = select_targets(TARGETS_SKILLS, agents, args.all)
        if not selected:
            print("  no agent skill directories detected")
        for name, dir_target in TARGETS_SKILLS.items():
            if name in selected:
                sync_skill_dir(dir_target, skills, sources, args.dry_run)
            elif dir_target.is_dir() and any(is_managed(read_link(p), sources) for p in dir_target.iterdir()):
                sync_skill_dir(dir_target, [], sources, args.dry_run)

    if not args.skills_only:
        selected = select_targets(TARGETS_DIGEST, agents, args.all)
        selected.setdefault("repo", TARGETS_DIGEST["repo"])
        for name, filepath_digest in TARGETS_DIGEST.items():
            if name in selected:
                body = build_digest(skills, relative=name == "repo", index=name != "claude")
                write_digest(filepath_digest, body, args.dry_run)
            else:
                remove_digest(filepath_digest, args.dry_run)

    if args.dry_run:
        print("dry run - nothing written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
